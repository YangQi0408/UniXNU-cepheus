#!/usr/bin/env python3
"""Build the FAT payload with the prebuilt cepheus (SM8150) kernel and ADT wrapper.

The kernel is the SM8150 XNU produced by the kernel step (guacamole's proven
build, identical silicon); the ADT is generated by scripts/make-cepheus-adt.py
from the iPhone X (D22AP) base tree with the cepheus device profile.
"""
import sys
import tomllib
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "unixnu" / "scripts"))
sys.path.insert(0, str(ROOT / "scripts"))

from unixnu import payload  # noqa: E402
from tree import assemble  # noqa: E402

WORK = ROOT / "out" / "cepheus"
TREE = assemble(WORK, ROOT / "unixnu", ROOT)
LOGS = WORK / "logs"
LOGS.mkdir(parents=True, exist_ok=True)

board = tomllib.loads((ROOT / "board.toml").read_text())
ctx = types.SimpleNamespace(
    board=board,
    tree=TREE,
    work=WORK,
    logs=LOGS,
    uefi=ROOT / "uefi",
    args=types.SimpleNamespace(
        kernel=ROOT / "inputs" / "cepheus" / "kernel.macho",
        kernel_arg=None,
        trust_cache=None,
        owner_trust_cache=None,
        data_ramdisk=None,
        skip_setup=False,
        unique_chip_id="0x5357454554000001",
    ),
)
payload.build(ctx)
